// newWinBackOffersCreateCommand returns the win-back offers create subcommand.
func newWinBackOffersCreateCommand(d *shared.Deps) *ffcli.Command {
	fs := d.NewFlagSet("create", flag.ExitOnError)

	subscriptionID := shared.BindResourceIDFlag(fs, "subscription-id", "subscriptions", "Subscription ID, product ID, or exact current name")
	appID := fs.String("app", "", "App Store Connect app ID (or ASC_APP_ID env; required when --subscription-id uses a product ID or name)")
	referenceName := fs.String("reference-name", "", "Reference name")
	offerID := fs.String("offer-id", "", "Offer ID")
	duration := fs.String("duration", "", "Offer duration: "+strings.Join(winBackOfferDurationValues, ", "))
	offerMode := fs.String("offer-mode", "", "Offer mode: "+strings.Join(winBackOfferModeValues, ", "))
	var periodCount optionalInt
	fs.Var(&periodCount, "period-count", "Number of periods (required)")
	var eligibilityPaidMonths optionalInt
	fs.Var(&eligibilityPaidMonths, "eligibility-paid-months", "Paid subscription duration in months (required)")
	var eligibilityLastSubscribedMin optionalInt
	fs.Var(&eligibilityLastSubscribedMin, "eligibility-last-subscribed-min", "Minimum months since last subscribed")
	var eligibilityLastSubscribedMax optionalInt
	fs.Var(&eligibilityLastSubscribedMax, "eligibility-last-subscribed-max", "Maximum months since last subscribed")
	var eligibilityWaitMonths optionalInt
	fs.Var(&eligibilityWaitMonths, "eligibility-wait-months", "Wait between offers in months (optional)")
	startDate := fs.String("start-date", "", "Start date (YYYY-MM-DD)")
	endDate := fs.String("end-date", "", "End date (YYYY-MM-DD)")
	priority := fs.String("priority", "", "Offer priority: "+strings.Join(winBackOfferPriorityValues, ", "))
	promotionIntent := fs.String("promotion-intent", "", "Promotion intent: "+strings.Join(winBackOfferPromotionIntentValues, ", "))
	priceIDs := shared.BindOnceCSVFlag(fs, "price", "Subscription price point ID(s), comma-separated (required for paid offer modes)")
	territories := shared.BindOnceCSVFlag(fs, "territory", "Territories for FREE_TRIAL offers, comma-separated (accepts alpha-2, alpha-3, or exact English country names)")
	targetPlanType := d.BindTargetSubscriptionPlanTypeFlag(fs)
	output := d.BindOutputFlags(fs)

	return &ffcli.Command{
		Name:       "create",
		ShortUsage: "asc win-back-offers create [flags]",
		ShortHelp:  "Create a win-back offer.",
		LongHelp: `Create a win-back offer.

Paid offer modes (PAY_AS_YOU_GO, PAY_UP_FRONT) require --price with
subscription price point IDs. FREE_TRIAL offers carry no price point, so
they require --territory instead.

Examples:
  asc win-back-offers create --subscription-id "SUB_ID" --reference-name "spring-2026" --offer-id "OFFER-1" --duration ONE_MONTH --offer-mode PAY_AS_YOU_GO --period-count 1 --eligibility-paid-months 6 --eligibility-last-subscribed-min 3 --eligibility-last-subscribed-max 12 --start-date "2026-02-01" --priority HIGH --price "SUBSCRIPTION_PRICE_POINT_ID"
  asc win-back-offers create --subscription-id "SUB_ID" --reference-name "spring-2026" --offer-id "OFFER-2" --duration ONE_MONTH --offer-mode FREE_TRIAL --period-count 1 --eligibility-paid-months 6 --eligibility-last-subscribed-min 3 --eligibility-last-subscribed-max 12 --start-date "2026-02-01" --priority HIGH --territory "USA,FRA"
  asc win-back-offers create --subscription-id "SUB_ID" --reference-name "spring-2026" --offer-id "OFFER-3" --duration ONE_MONTH --offer-mode FREE_TRIAL --period-count 1 --eligibility-paid-months 6 --eligibility-last-subscribed-min 3 --eligibility-last-subscribed-max 12 --start-date "2026-02-01" --priority HIGH --territory "USA" --target-subscription-plan-type MONTHLY`,
		FlagSet:   fs,
		UsageFunc: d.DefaultUsageFunc,
		Exec: func(ctx context.Context, args []string) error {
			subscription := strings.TrimSpace(*subscriptionID)
			if subscription == "" {
				return d.RequiredFlag("--subscription-id")
			}

			name := strings.TrimSpace(*referenceName)
			if name == "" {
				return d.RequiredFlag("--reference-name")
			}

			offer := strings.TrimSpace(*offerID)
			if offer == "" {
				return d.RequiredFlag("--offer-id")
			}

			if strings.TrimSpace(*duration) == "" {
				return d.RequiredFlag("--duration")
			}
			durationValue, err := normalizeWinBackOfferDuration(*duration)
			if err != nil {
				return d.UsageErrorfCtx(ctx, "win-back-offers create: %v", err)
			}

			if strings.TrimSpace(*offerMode) == "" {
				return d.RequiredFlag("--offer-mode")
			}
			offerModeValue, err := normalizeWinBackOfferMode(*offerMode)
			if err != nil {
				return d.UsageErrorfCtx(ctx, "win-back-offers create: %v", err)
			}

			if !periodCount.set {
				return d.RequiredFlag("--period-count")
			}
			if periodCount.value <= 0 {
				return d.UsageErrorCtx(ctx, "win-back-offers create: --period-count must be greater than 0")
			}

			if !eligibilityPaidMonths.set {
				return d.RequiredFlag("--eligibility-paid-months")
			}
			if eligibilityPaidMonths.value < 0 {
				return d.UsageErrorCtx(ctx, "win-back-offers create: --eligibility-paid-months must be 0 or greater")
			}

			if !eligibilityLastSubscribedMin.set && !eligibilityLastSubscribedMax.set {
				fmt.Fprintln(d.IO.ErrOut, "Error: --eligibility-last-subscribed-min or --eligibility-last-subscribed-max is required")
				return shared.MissingRequiredUsageError("")
			}
			if eligibilityLastSubscribedMin.set && eligibilityLastSubscribedMin.value < 0 {
				return d.UsageErrorCtx(ctx, "win-back-offers create: eligibility last subscribed min must be 0 or greater")
			}
			if eligibilityLastSubscribedMax.set && eligibilityLastSubscribedMax.value < 0 {
				return d.UsageErrorCtx(ctx, "win-back-offers create: eligibility last subscribed max must be 0 or greater")
			}
			if eligibilityLastSubscribedMin.set && eligibilityLastSubscribedMax.set && eligibilityLastSubscribedMin.value > eligibilityLastSubscribedMax.value {
				return d.UsageErrorCtx(ctx, "win-back-offers create: eligibility last subscribed min must be less than or equal to max")
			}

			rangeValue := asc.IntegerRange{}
			if eligibilityLastSubscribedMin.set {
				rangeValue.Minimum = &eligibilityLastSubscribedMin.value
			}
			if eligibilityLastSubscribedMax.set {
				rangeValue.Maximum = &eligibilityLastSubscribedMax.value
			}

			if strings.TrimSpace(*startDate) == "" {
				return d.RequiredFlag("--start-date")
			}
			normalizedStartDate, err := shared.NormalizeDate(*startDate, "--start-date")
			if err != nil {
				return d.UsageErrorfCtx(ctx, "win-back-offers create: %v", err)
			}

			if strings.TrimSpace(*priority) == "" {
				return d.RequiredFlag("--priority")
			}
			priorityValue, err := normalizeWinBackOfferPriority(*priority)
			if err != nil {
				return d.UsageErrorfCtx(ctx, "win-back-offers create: %v", err)
			}

			isFreeTrial := offerModeValue == asc.SubscriptionOfferModeFreeTrial
			priceProvided := false
			fs.Visit(func(f *flag.Flag) { priceProvided = priceProvided || f.Name == "price" })
			prices := shared.SplitCSV(priceIDs.String())
			var freeTrialTerritories []string
			if isFreeTrial {
				if priceProvided {
					fmt.Fprintln(d.IO.ErrOut, "Error: --price is not supported when --offer-mode is FREE_TRIAL; use --territory to choose territories")
					return shared.WithDiagnostic(flag.ErrHelp, shared.DiagnosticConflictingInput, "--price")
				}
				freeTrialTerritories, err = shared.NormalizeASCTerritoryCSV(territories.String())
				if err != nil {
					return d.UsageErrorfCtx(ctx, "win-back-offers create: %v", err)
				}
				if len(freeTrialTerritories) == 0 {
					fmt.Fprintln(d.IO.ErrOut, "Error: --territory is required when --offer-mode is FREE_TRIAL")
					return shared.MissingRequiredUsageError("--territory")
				}
			} else {
				if strings.TrimSpace(territories.String()) != "" {
					fmt.Fprintln(d.IO.ErrOut, "Error: --territory is only supported when --offer-mode is FREE_TRIAL")
					return shared.WithDiagnostic(flag.ErrHelp, shared.DiagnosticConflictingInput, "--territory")
				}
				if len(prices) == 0 {
					return d.RequiredFlag("--price")
				}
			}

			if eligibilityWaitMonths.set && eligibilityWaitMonths.value < 0 {
				return d.UsageErrorCtx(ctx, "win-back-offers create: --eligibility-wait-months must be 0 or greater")
			}

			normalizedEndDate := ""
			if strings.TrimSpace(*endDate) != "" {
				normalizedEndDate, err = shared.NormalizeDate(*endDate, "--end-date")
				if err != nil {
					return d.UsageErrorfCtx(ctx, "win-back-offers create: %v", err)
				}
			}

			var promotionIntentValue *asc.WinBackOfferPromotionIntent
			if strings.TrimSpace(*promotionIntent) != "" {
				intent, err := normalizeWinBackOfferPromotionIntent(*promotionIntent)
				if err != nil {
					return d.UsageErrorfCtx(ctx, "win-back-offers create: %v", err)
				}
				promotionIntentValue = &intent
			}

			// Win-back offer prices don't exist before the offer does, so
			// inline-create them in `included` with temp `${price-N}` IDs.
			// Paid modes pair each entry with territory (decoded from the
			// price point ID itself) + subscriptionPricePoint relationships;
			// FREE_TRIAL entries carry only the territory because the API
			// rejects price points on free offers.
			var priceData []asc.ResourceData
			var includedPrices []asc.WinBackOfferPriceInlineCreate
			appendInlinePrice := func(relationships *asc.WinBackOfferPriceRelationships) {
				tempID := fmt.Sprintf("${price-%d}", len(priceData)+1)
				priceData = append(priceData, asc.ResourceData{
					Type: asc.ResourceTypeWinBackOfferPrices,
					ID:   tempID,
				})
				includedPrices = append(includedPrices, asc.WinBackOfferPriceInlineCreate{
					Type:          asc.ResourceTypeWinBackOfferPrices,
					ID:            tempID,
					Relationships: relationships,
				})
			}
			if isFreeTrial {
				for _, territory := range freeTrialTerritories {
					appendInlinePrice(&asc.WinBackOfferPriceRelationships{
						Territory: asc.Relationship{
							Data: asc.ResourceData{
								Type: asc.ResourceTypeTerritories,
								ID:   territory,
							},
						},
					})
				}
			} else {
				for _, priceID := range prices {
					territory, err := territoryFromPricePointID(priceID)
					if err != nil {
						return d.UsageErrorfCtx(ctx, "win-back-offers create: %v", err)
					}
					appendInlinePrice(&asc.WinBackOfferPriceRelationships{
						Territory: asc.Relationship{
							Data: asc.ResourceData{
								Type: asc.ResourceTypeTerritories,
								ID:   territory,
							},
						},
						SubscriptionPricePoint: &asc.Relationship{
							Data: asc.ResourceData{
								Type: asc.ResourceTypeSubscriptionPricePoints,
								ID:   priceID,
							},
						},
					})
				}
			}

			planType, err := targetPlanType()
			if err != nil {
				return err
			}

			var waitBetween *int
			if eligibilityWaitMonths.set {
				waitBetween = &eligibilityWaitMonths.value
			}

			var endDateValue *string
			if normalizedEndDate != "" {
				endDateValue = &normalizedEndDate
			}

			client, err := d.Client()
			if err != nil {
				return fmt.Errorf("win-back-offers create: %w", err)
			}

			appSelector := d.ResolveAppSelector(strings.TrimSpace(*appID))
			if err := d.RequireAppForStableSelector(appSelector.Value, subscription, "--subscription-id"); err != nil {
				return err
			}
			resolveCtx, resolveCancel := d.Timeout(ctx)
			subscription, err = shared.ResolveSubscriptionIDWithAppSelector(resolveCtx, client, appSelector, subscription)
			resolveCancel()
			if err != nil {
				return err
			}

			requestCtx, cancel := d.Timeout(ctx)
			defer cancel()

			req := asc.WinBackOfferCreateRequest{
				Data: asc.WinBackOfferCreateData{
					Type: asc.ResourceTypeWinBackOffers,
					Attributes: asc.WinBackOfferCreateAttributes{
						ReferenceName: name,
						OfferID:       offer,
						Duration:      durationValue,
						OfferMode:     offerModeValue,
						PeriodCount:   periodCount.value,
						CustomerEligibilityPaidSubscriptionDurationInMonths: eligibilityPaidMonths.value,
						CustomerEligibilityTimeSinceLastSubscribedInMonths:  rangeValue,
						CustomerEligibilityWaitBetweenOffersInMonths:        waitBetween,
						StartDate:                  normalizedStartDate,
						EndDate:                    endDateValue,
						Priority:                   priorityValue,
						PromotionIntent:            promotionIntentValue,
						TargetSubscriptionPlanType: planType,
					},
					Relationships: asc.WinBackOfferCreateRelationships{
						Subscription: asc.Relationship{
							Data: asc.ResourceData{
								Type: asc.ResourceTypeSubscriptions,
								ID:   subscription,
							},
						},
						Prices: asc.RelationshipList{Data: priceData},
					},
				},
				Included: includedPrices,
			}

			resp, err := client.CreateWinBackOffer(requestCtx, req)
			if err != nil {
				return fmt.Errorf("win-back-offers create: failed to create: %w", err)
			}

			return d.PrintOutput(resp, *output.Output, *output.Pretty)
		},
	}
}

