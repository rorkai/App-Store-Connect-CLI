func TestProfileCreateNameForTargetAcceptsOperationDateBoundary(t *testing.T) {
	createdAt := time.Date(2026, time.August, 30, 23, 59, 59, 0, time.Local)
	observedAt := createdAt.Add(2 * time.Second)
	got := profileCreateNameForTarget("IOS_APP_DEVELOPMENT", "com.example.new", createdAt)
	if got == profileCreateNameForTarget("IOS_APP_DEVELOPMENT", "com.example.new", observedAt) {
		t.Fatal("test fixture must cross a local date boundary")
	}
	if !profileCreateNameForTargetInTimeWindow(got, "IOS_APP_DEVELOPMENT", "com.example.new", createdAt, observedAt) {
		t.Fatalf("profile name %q was rejected for an operation spanning %s to %s", got, createdAt, observedAt)
	}
}

// profileCreateNameForTargetInTimeWindow keeps this integration assertion stable
// when resolving assets and publishing the repository crosses local midnight.
// The name is generated by production at an instant between these observations,
// so either boundary date is valid without adding a production clock seam.
func profileCreateNameForTargetInTimeWindow(got, profileType, bundleIdentifier string, startedAt, finishedAt time.Time) bool {
	if finishedAt.Before(startedAt) {
		startedAt, finishedAt = finishedAt, startedAt
	}
	return got == profileCreateNameForTarget(profileType, bundleIdentifier, startedAt) ||
		got == profileCreateNameForTarget(profileType, bundleIdentifier, finishedAt)
}

