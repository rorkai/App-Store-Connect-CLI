package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

const header = "// Code generated by openapigen from the App Store Connect OpenAPI spec; DO NOT EDIT."

// Generate renders the Go file of one family.
func Generate(spec *Spec, fam *Family) ([]byte, error) {
	var body bytes.Buffer
	for _, name := range fam.Types {
		src, err := renderType(spec, name)
		if err != nil {
			return nil, fmt.Errorf("%s: type %s: %w", fam.Tag, name, err)
		}
		body.WriteString(src)
	}
	for _, b := range fam.Operations {
		src, err := renderMethod(spec, b)
		if err != nil {
			return nil, fmt.Errorf("%s: %s: %w", fam.Tag, b.Operation, err)
		}
		body.WriteString(src)
	}

	var out bytes.Buffer
	out.WriteString(header + "\n\npackage asc\n\n")
	var imports []string
	for _, imp := range []struct{ path, use string }{
		{"context", "context."}, {"fmt", "fmt."}, {"net/http", "http."}, {"strings", "strings."},
	} {
		if strings.Contains(body.String(), imp.use) {
			imports = append(imports, strconv.Quote(imp.path))
		}
	}
	if len(imports) > 0 {
		out.WriteString("import (\n" + strings.Join(imports, "\n") + "\n)\n\n")
	}
	out.Write(body.Bytes())
	return format.Source(out.Bytes())
}

// renderType renders a type from its name; the suffix picks the rule.
func renderType(spec *Spec, name string) (string, error) {
	if resource, many, ok := spec.resourceOf(name); ok && strings.HasSuffix(name, "Response") {
		generic := "SingleResponse"
		if many {
			generic = "Response"
		}
		return fmt.Sprintf("// %s is the %s schema.\ntype %s = %s[%sAttributes]\n\n", name, name, name, generic, resource), nil
	}
	if base, ok := strings.CutSuffix(name, "Request"); ok {
		if _, found := spec.Schema(name); found {
			return fmt.Sprintf("// %s is the %s schema.\ntype %s struct {\nData %sData `json:\"data\"`\n}\n\n", name, name, name, base), nil
		}
	}
	if base, ok := strings.CutSuffix(name, "Data"); ok {
		request := base + "Request"
		data, err := requestData(spec, request)
		if err != nil {
			return "", err
		}
		var fields []string
		for _, prop := range data.Properties {
			switch prop.Name {
			case "type":
				fields = append(fields, "Type ResourceType `json:\"type\"`")
			case "id":
				fields = append(fields, "ID string `json:\"id\"`")
			case "attributes":
				if data.requires("attributes") {
					fields = append(fields, fmt.Sprintf("Attributes %sAttributes `json:\"attributes\"`", base))
				} else {
					fields = append(fields, fmt.Sprintf("Attributes *%sAttributes `json:\"attributes,omitempty\"`", base))
				}
			default:
				return "", fmt.Errorf("data property %q is not supported", prop.Name)
			}
		}
		return structDecl(name, "the data object of the "+request+" schema", fields), nil
	}
	if base, ok := strings.CutSuffix(name, "Attributes"); ok {
		if data, err := requestData(spec, base+"Request"); err == nil {
			attrs := data.Properties.Get("attributes")
			if attrs == nil {
				return "", fmt.Errorf("%sRequest has no attributes", base)
			}
			fields, err := attributeFields(attrs, true)
			if err != nil {
				return "", err
			}
			return structDecl(name, "the data.attributes object of the "+base+"Request schema", fields), nil
		}
		resource, ok := spec.Schema(base)
		if !ok || resource.Properties.Get("attributes") == nil {
			return "", fmt.Errorf("no resource schema %s", base)
		}
		fields, err := attributeFields(resource.Properties.Get("attributes"), false)
		if err != nil {
			return "", err
		}
		return structDecl(name, "the attributes object of the "+base+" schema", fields), nil
	}
	return "", fmt.Errorf("no rule for this name")
}

func requestData(spec *Spec, request string) (*Schema, error) {
	sch, ok := spec.Schema(request)
	if !ok {
		return nil, fmt.Errorf("no schema %s", request)
	}
	data := sch.Properties.Get("data")
	if data == nil || data.Type != "object" {
		return nil, fmt.Errorf("%s has no data object", request)
	}
	return data, nil
}

func structDecl(name, what string, fields []string) string {
	return fmt.Sprintf("// %s is %s.\ntype %s struct {\n%s\n}\n\n", name, what, name, strings.Join(fields, "\n"))
}

// attributeFields maps attributes to fields in spec order. Response attributes
// are values with omitempty. Request attributes keep required fields as values
// without omitempty and make optional scalars pointers.
func attributeFields(attrs *Schema, request bool) ([]string, error) {
	var fields []string
	for _, prop := range attrs.Properties {
		typ, scalar, err := goType(prop.Schema)
		if err != nil {
			return nil, fmt.Errorf("attribute %q: %w", prop.Name, err)
		}
		tag := prop.Name + ",omitempty"
		if request && attrs.requires(prop.Name) {
			tag = prop.Name
		} else if request && scalar {
			typ = "*" + typ
		}
		fields = append(fields, fmt.Sprintf("%s %s `json:%q`", goName(prop.Name), typ, tag))
	}
	return fields, nil
}

func goType(s *Schema) (string, bool, error) {
	switch {
	case s.Ref != "":
		return "", false, fmt.Errorf("$ref %s is not supported", refName(s.Ref))
	case s.Type == "string":
		return "string", true, nil
	case s.Type == "integer":
		return "int", true, nil
	case s.Type == "number":
		return "float64", true, nil
	case s.Type == "boolean":
		return "bool", true, nil
	case s.Type == "array" && s.Items != nil && s.Items.Ref == "" && s.Items.Type == "string":
		return "[]string", false, nil
	}
	return "", false, fmt.Errorf("type %q is not supported", s.Type)
}

// method collects the parts of one generated method.
type method struct {
	b      *OpBind
	op     *Operation
	params []string // signature after ctx
	result string   // "error" or "(*T, error)"
	pre    []string
}

func renderMethod(spec *Spec, b *OpBind) (string, error) {
	op, ok := spec.Operation(b.Operation)
	if !ok {
		return "", fmt.Errorf("operation not in spec")
	}
	if len(b.Params) != strings.Count(op.Path, "{") {
		return "", fmt.Errorf("%d params for path %s", len(b.Params), op.Path)
	}
	switch b.Check {
	case checkInline, checkTrim, checkRequire, checkRaw:
	default:
		return "", fmt.Errorf("unknown check style %q", b.Check)
	}
	if b.CheckFirst && (op.Method != "GET" || b.Options == "" || (b.Check != checkTrim && b.Check != checkRequire)) {
		return "", fmt.Errorf("checkFirst needs a paged read with trim or require checks")
	}
	write := (op.Method == "PATCH" && strings.HasSuffix(op.Request, "UpdateRequest")) ||
		(op.Method == "POST" && strings.HasSuffix(op.Request, "CreateRequest"))
	if (b.Attrs != "" || b.SkipEmptyAttributes) && !write {
		return "", fmt.Errorf("attributes bindings need a create or update request")
	}
	m := &method{b: b, op: op}
	if len(b.Params) > 0 {
		m.params = append(m.params, strings.Join(b.Params, ", ")+" string")
	}
	response := b.Response
	if response == "" {
		response = op.Response
	}

	var call string
	switch {
	case op.Method == "GET":
		if response == "" {
			return "", fmt.Errorf("no response schema")
		}
		call = m.read(response)
	case op.Method == "DELETE" && op.Request == "":
		m.result = "error"
		m.checks()
		call = fmt.Sprintf("return sendNoContent(ctx, c, http.MethodDelete, %s, nil)", m.path())
	case strings.HasSuffix(op.Request, "LinkagesRequest"):
		linkType, err := linkageType(spec, op.Request)
		if err != nil {
			return "", err
		}
		if b.IDs == "" {
			return "", fmt.Errorf("relationship change needs ids")
		}
		m.params = append(m.params, b.IDs+" []string")
		m.result = "error"
		m.checks()
		m.pre = append(m.pre, fmt.Sprintf("payload := RelationshipRequest{\nData: buildRelationshipData(%s, %s),\n}", resourceTypeConst(linkType), b.IDs))
		call = fmt.Sprintf("return sendNoContent(ctx, c, http.Method%s, %s, payload)", methodConst(op.Method), m.path())
	case write:
		if response == "" {
			return "", fmt.Errorf("no response schema")
		}
		m.result = "(*" + response + ", error)"
		payload, err := m.payload(spec)
		if err != nil {
			return "", err
		}
		m.pre = append(m.pre, payload)
		call = fmt.Sprintf("return sendJSON[%s](ctx, c, writeRequest{\nMethod: http.Method%s,\nPath: %s,\nPayload: payload,\n})", response, methodConst(op.Method), m.path())
	default:
		return "", fmt.Errorf("%s with request %q is not supported", op.Method, op.Request)
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// %s sends %s %s (%s).\n", b.Name, op.Method, op.Path, op.ID)
	fmt.Fprintf(&out, "func (c *Client) %s(%s) %s {\n", b.Name, strings.Join(append([]string{"ctx context.Context"}, m.params...), ", "), m.result)
	for _, line := range m.pre {
		out.WriteString(line + "\n")
	}
	out.WriteString(call + "\n}\n\n")
	return out.String(), nil
}

func (m *method) read(response string) string {
	m.result = "(*" + response + ", error)"
	fields := []string{"Path: " + m.path()}
	if m.b.CheckFirst {
		m.checks()
	}
	if m.b.Options != "" {
		m.params = append(m.params, "opts ..."+m.b.Options)
		m.pre = append(m.pre, "query := applyOptions(opts)")
		fields = append(fields, fmt.Sprintf("Query: %s(query)", m.b.Query), "Next: query.nextURL")
		if m.b.NextContext != "" {
			fields = append(fields, "NextContext: "+strconv.Quote(m.b.NextContext))
		}
	}
	if m.b.ParseErr != "" {
		fields = append(fields, "ParseErr: "+strconv.Quote(m.b.ParseErr))
	}
	if !m.b.CheckFirst {
		m.checks()
	}
	return fmt.Sprintf("return getJSON[%s](ctx, c, readRequest{\n%s,\n})", response, strings.Join(fields, ",\n"))
}

// checks adds the trim and blank checks of the path parameters.
func (m *method) checks() {
	if m.b.Check == checkInline || m.b.Check == checkRaw {
		return
	}
	for _, p := range m.b.Params {
		m.pre = append(m.pre, fmt.Sprintf("%s = strings.TrimSpace(%s)", p, p))
	}
	if m.b.Check != checkRequire {
		return
	}
	zero := ""
	if m.result != "error" {
		zero = "nil, "
	}
	for i, p := range m.b.Params {
		msg := p + " is required"
		if i < len(m.b.Messages) {
			msg = m.b.Messages[i]
		}
		cond := p + ` == ""`
		if m.b.Options != "" && !m.b.CheckFirst {
			cond = `query.nextURL == "" && ` + cond
		}
		m.pre = append(m.pre, fmt.Sprintf("if %s {\nreturn %sfmt.Errorf(%s)\n}", cond, zero, strconv.Quote(msg)))
	}
}

// arg is a path parameter as the request uses it.
func (m *method) arg(i int) string {
	if m.b.Check == checkInline {
		return "strings.TrimSpace(" + m.b.Params[i] + ")"
	}
	return m.b.Params[i]
}

func (m *method) path() string {
	if len(m.b.Params) == 0 {
		return strconv.Quote(m.op.Path)
	}
	format := m.op.Path
	var args []string
	for i := range m.b.Params {
		start := strings.Index(format, "{")
		end := strings.Index(format, "}")
		format = format[:start] + "%s" + format[end+1:]
		args = append(args, m.arg(i))
	}
	return fmt.Sprintf("fmt.Sprintf(%s, %s)", strconv.Quote(format), strings.Join(args, ", "))
}

// payload builds the create or update body; the attributes argument is
// always named attrs.
func (m *method) payload(spec *Spec) (string, error) {
	base := strings.TrimSuffix(m.op.Request, "Request")
	data, err := requestData(spec, m.op.Request)
	if err != nil {
		return "", err
	}
	typ := data.Properties.Get("type")
	if typ == nil || len(typ.Enum) != 1 {
		return "", fmt.Errorf("%s has no single type", m.op.Request)
	}
	fields := []string{"Type: " + resourceTypeConst(typ.Enum[0])}
	if data.Properties.Get("id") != nil {
		if len(m.b.Params) != 1 {
			return "", fmt.Errorf("update needs one path parameter")
		}
		fields = append(fields, "ID: "+m.arg(0))
	}
	if data.Properties.Get("relationships") != nil {
		return "", fmt.Errorf("relationships in %s are not supported", m.op.Request)
	}
	if err := m.checkAttrs(data); err != nil {
		return "", err
	}
	var step string
	if attrs := data.Properties.Get("attributes"); attrs != nil {
		typ := base + "Attributes"
		if m.b.Attrs == attrsPointer {
			typ = "*" + typ
		}
		m.params = append(m.params, "attrs "+typ)
		switch {
		case m.b.SkipEmptyAttributes:
			step = "\n" + attributesIfSet(attrs)
		case data.requires("attributes") || m.b.Attrs != "":
			fields = append(fields, "Attributes: attrs")
		default:
			fields = append(fields, "Attributes: &attrs")
		}
	}
	m.checks()
	return fmt.Sprintf("payload := %s{\nData: %sData{\n%s,\n},\n}", m.op.Request, base, strings.Join(fields, ",\n")) + step, nil
}

// checkAttrs rejects attributes bindings the request data cannot take.
func (m *method) checkAttrs(data *Schema) error {
	attrs := data.Properties.Get("attributes")
	optional := attrs != nil && !data.requires("attributes")
	switch m.b.Attrs {
	case "":
	case attrsValue, attrsPointer:
		if !optional {
			return fmt.Errorf("attrs %q needs optional attributes", m.b.Attrs)
		}
	default:
		return fmt.Errorf("unknown attrs %q", m.b.Attrs)
	}
	if m.b.SkipEmptyAttributes && (!optional || m.b.Attrs != "" || len(attrs.Required) > 0 || len(attrs.Properties) == 0) {
		return fmt.Errorf("skipEmptyAttributes needs optional attributes, none of them required, passed by value")
	}
	return nil
}

// attributesIfSet attaches the attributes only when one of them is set. No
// attribute is required, so a request attributes type holds each as a
// nillable field.
func attributesIfSet(attrs *Schema) string {
	var set []string
	for _, prop := range attrs.Properties {
		set = append(set, "attrs."+goName(prop.Name)+" != nil")
	}
	return fmt.Sprintf("if %s {\npayload.Data.Attributes = &attrs\n}", strings.Join(set, " || "))
}

func linkageType(spec *Spec, request string) (string, error) {
	sch, ok := spec.Schema(request)
	if !ok {
		return "", fmt.Errorf("no schema %s", request)
	}
	data := sch.Properties.Get("data")
	if data == nil || data.Items == nil || data.Items.Properties.Get("type") == nil || len(data.Items.Properties.Get("type").Enum) != 1 {
		return "", fmt.Errorf("%s is not a to-many linkage request", request)
	}
	return data.Items.Properties.Get("type").Enum[0], nil
}

func methodConst(method string) string {
	return upperFirst(strings.ToLower(method))
}
