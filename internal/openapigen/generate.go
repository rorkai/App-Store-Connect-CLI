const header = "// Code generated by openapigen from the App Store Connect OpenAPI spec; DO NOT EDIT."

// Generate renders the Go file of one family.
func Generate(spec *Spec, fam *Family) ([]byte, error) {
	if err := checkArgTypes(spec, fam); err != nil {
		return nil, fmt.Errorf("%s: %w", fam.Tag, err)
	}
	if err := checkRefTypes(spec, fam); err != nil {
		return nil, fmt.Errorf("%s: %w", fam.Tag, err)
	}
	if err := checkGoTypes(fam); err != nil {
		return nil, fmt.Errorf("%s: %w", fam.Tag, err)
	}
	var body bytes.Buffer
	for _, name := range fam.Types {
		src, err := renderType(spec, fam, name)
		if err != nil {
			return nil, fmt.Errorf("%s: type %s: %w", fam.Tag, name, err)
		}
		body.WriteString(src)
	}
	for _, b := range fam.Operations {
		src, err := renderMethod(spec, fam, b)
		if err != nil {
			return nil, fmt.Errorf("%s: %s: %w", fam.Tag, b.Operation, err)
		}
		body.WriteString(src)
	}
	queries, err := renderQueries(spec, fam)
	if err != nil {
		return nil, err
	}
	body.WriteString(queries)

	var out bytes.Buffer
	out.WriteString(header + "\n\npackage asc\n\n")
	var imports []string
	for _, imp := range []struct{ path, use string }{
		{"context", "context."}, {"fmt", "fmt."}, {"net/http", "http."}, {"net/url", "url.Values"}, {"strings", "strings."},
	} {
		if strings.Contains(body.String(), imp.use) {
			imports = append(imports, strconv.Quote(imp.path))
		}
	}
	if len(imports) > 0 {
		out.WriteString("import (\n" + strings.Join(imports, "\n") + "\n)\n\n")
	}
	out.Write(body.Bytes())
	return format.Source(out.Bytes())
}

// renderType renders a type of a family from its name; the suffix picks the
// rule.
func renderType(spec *Spec, fam *Family, name string) (string, error) {
	if rel := fam.relationshipsNamed(name); rel != nil {
		return relationshipsStruct(spec, rel, name)
	}
	if resource, many, ok := spec.resourceOf(name); ok && strings.HasSuffix(name, "Response") {
		generic := "SingleResponse"
		if many {
			generic = "Response"
		}
		return fmt.Sprintf("// %s is the %s schema.\ntype %s = %s[%s]\n\n", goTypeName(name), name, goTypeName(name), generic, fam.goType(resource+"Attributes")), nil
	}
	if base, ok := strings.CutSuffix(name, "Request"); ok {
		if _, found := spec.Schema(name); found {
			return fmt.Sprintf("// %s is the %s schema.\ntype %s struct {\nData %s `json:\"data\"`\n}\n\n", goTypeName(name), name, goTypeName(name), fam.goType(base+"Data")), nil
		}
	}
	if base, ok := strings.CutSuffix(name, "Data"); ok {
		request := base + "Request"
		data, err := requestData(spec, request)
		if err != nil {
			return "", err
		}
		var fields []string
		for _, prop := range data.Properties {
			switch prop.Name {
			case "type":
				fields = append(fields, "Type ResourceType `json:\"type\"`")
			case "id":
				fields = append(fields, "ID string `json:\"id\"`")
			case "attributes":
				if data.requires("attributes") {
					fields = append(fields, fmt.Sprintf("Attributes %s `json:\"attributes\"`", fam.goType(base+"Attributes")))
				} else {
					fields = append(fields, fmt.Sprintf("Attributes *%s `json:\"attributes,omitempty\"`", fam.goType(base+"Attributes")))
				}
			case "relationships":
				rel, err := fam.relationshipsOf(name)
				if err != nil {
					return "", err
				}
				tag := "relationships"
				if rel.OmitEmpty {
					tag += ",omitempty"
				}
				fields = append(fields, fmt.Sprintf("Relationships %s `json:%q`", rel.Type, tag))
			default:
				return "", fmt.Errorf("data property %q is not supported", prop.Name)
			}
		}
		return structDecl(goTypeName(name), "the data object of the "+request+" schema", fields), nil
	}
	if base, ok := strings.CutSuffix(name, "Attributes"); ok {
		if data, err := requestData(spec, base+"Request"); err == nil {
			attrs := data.Properties.Get("attributes")
			if attrs == nil {
				return "", fmt.Errorf("%sRequest has no attributes", base)
			}
			fields, err := attributeFields(spec, fam, attrs, true)
			if err != nil {
				return "", err
			}
			return structDecl(goTypeName(name), "the data.attributes object of the "+base+"Request schema", fields), nil
		}
		resource, ok := spec.Schema(base)
		if !ok || resource.Properties.Get("attributes") == nil {
			return "", fmt.Errorf("no resource schema %s", base)
		}
		fields, err := attributeFields(spec, fam, resource.Properties.Get("attributes"), false)
		if err != nil {
			return "", err
		}
		return structDecl(goTypeName(name), "the attributes object of the "+base+" schema", fields), nil
	}
	return "", fmt.Errorf("no rule for this name")
}

// relationshipsStruct renders the relationships type a create's data names,
// in spec order. A relationship is a Relationship, or a RelationshipList when
// it is to-many; a pointer when the data holds the type by pointer or the
// relationship is optional; omitempty when it is optional.
func relationshipsStruct(spec *Spec, rel *RelBind, name string) (string, error) {
	request := strings.TrimSuffix(rel.Data, "Data") + "Request"
	data, err := requestData(spec, request)
	if err != nil {
		return "", err
	}
	rels := data.Properties.Get("relationships")
	if rels == nil {
		return "", fmt.Errorf("%s has no relationships", request)
	}
	var fields []string
	for _, prop := range rels.Properties {
		typ, err := linkType(rel, rels, prop.Name)
		if err != nil {
			return "", err
		}
		tag := prop.Name
		if !rels.requires(prop.Name) {
			tag += ",omitempty"
		}
		fields = append(fields, fmt.Sprintf("%s %s `json:%q`", goName(prop.Name), typ, tag))
	}
	return structDecl(name, "the data.relationships object of the "+request+" schema", fields), nil
}

// linkType is the Go type of one relationship of a create, and of the field
// that holds it in the relationships type.
func linkType(rel *RelBind, rels *Schema, name string) (string, error) {
	prop := rels.Properties.Get(name)
	if prop == nil || prop.Properties.Get("data") == nil {
		return "", fmt.Errorf("no relationship %q", name)
	}
	typ := "Relationship"
	switch data := prop.Properties.Get("data"); {
	case data.Type == "array":
		typ = "RelationshipList"
	case data.Type != "object":
		return "", fmt.Errorf("relationship %q has data of type %q", name, data.Type)
	}
	if strings.HasPrefix(rel.Type, "*") || !rels.requires(name) {
		typ = "*" + typ
	}
	return typ, nil
}

func requestData(spec *Spec, request string) (*Schema, error) {
	sch, ok := spec.Schema(request)
	if !ok {
		return nil, fmt.Errorf("no schema %s", request)
	}
	data := sch.Properties.Get("data")
	if data == nil || data.Type != "object" {
		return nil, fmt.Errorf("%s has no data object", request)
	}
	return data, nil
}

func structDecl(name, what string, fields []string) string {
	return fmt.Sprintf("// %s is %s.\ntype %s struct {\n%s\n}\n\n", name, what, name, strings.Join(fields, "\n"))
}

// attributeFields maps attributes to fields in spec order. Response attributes
// are values with omitempty. Request attributes keep required fields as values
// without omitempty and make optional scalars pointers.
func attributeFields(spec *Spec, fam *Family, attrs *Schema, request bool) ([]string, error) {
	var fields []string
	for _, prop := range attrs.Properties {
		typ, scalar, err := goType(prop.Schema)
		if isRef(prop.Schema) {
			typ, scalar, err = refType(spec, fam, prop.Schema, request && attrs.requires(prop.Name))
		}
		if err != nil {
			return nil, fmt.Errorf("attribute %q: %w", prop.Name, err)
		}
		tag := prop.Name + ",omitempty"
		if request && attrs.requires(prop.Name) {
			tag = prop.Name
		} else if request && scalar {
			typ = "*" + typ
		}
		fields = append(fields, fmt.Sprintf("%s %s `json:%q`", goName(prop.Name), typ, tag))
	}
	return fields, nil
}

func goType(s *Schema) (string, bool, error) {
	switch {
	case s.Ref != "":
		return "", false, fmt.Errorf("$ref %s is not supported", refName(s.Ref))
	case s.Type == "string":
		return "string", true, nil
	case s.Type == "integer":
		return "int", true, nil
	case s.Type == "number":
		return "float64", true, nil
	case s.Type == "boolean":
		return "bool", true, nil
	case s.Type == "array" && s.Items != nil && s.Items.Ref == "" && s.Items.Type == "string":
		return "[]string", false, nil
	}
	return "", false, fmt.Errorf("type %q is not supported", s.Type)
}

// isRef reports whether an attribute references a schema, or is a list of
// references.
func isRef(s *Schema) bool {
	return s.Ref != "" || (s.Type == "array" && s.Items != nil && s.Items.Ref != "")
}

// refType is the Go type of an attribute that references an enum or object
// schema, or of a list of them: the type of the schema's name unless the
// family records another. An enum is a scalar. An object is a pointer unless
// the request requires it.
func refType(spec *Spec, fam *Family, s *Schema, required bool) (string, bool, error) {
	list := s.Ref == ""
	if list {
		s = s.Items
	}
	name := refName(s.Ref)
	kind, err := refKind(spec, name)
	if err != nil {
		return "", false, err
	}
	typ := fam.refType(name)
	switch {
	case list:
		return "[]" + typ, false, nil
	case kind == "enum":
		return typ, true, nil
	case required:
		return typ, false, nil
	}
	return "*" + typ, false, nil
}

// refKind is "enum" or "object" for a schema an attribute can reference.
func refKind(spec *Spec, name string) (string, error) {
	ref, ok := spec.Schema(name)
	switch {
	case !ok:
		return "", fmt.Errorf("no schema %s", name)
	case ref.Type == "string" && len(ref.Enum) > 0:
		return "enum", nil
	case ref.Type == "object" && len(ref.Properties) > 0:
		return "object", nil
	}
	return "", fmt.Errorf("$ref %s is neither an enum nor an object with properties", name)
}

// checkRefTypes rejects a record the generator cannot use: one for a schema
// that is no enum or object, with a type that is no type name, with "string"
// for an object, or a second one for the same schema.
func checkRefTypes(spec *Spec, fam *Family) error {
	seen := map[string]bool{}
	for _, r := range fam.RefTypes {
		if err := checkRefType(spec, r); err != nil {
			return err
		}
		if seen[r.Schema] {
			return fmt.Errorf("schema %s is recorded twice", r.Schema)
		}
		seen[r.Schema] = true
	}
	return nil
}

func checkRefType(spec *Spec, r *RefType) error {
	kind, err := refKind(spec, r.Schema)
	switch {
	case err != nil:
		return err
	case r.Type == "string" && kind == "enum":
		return nil
	case !refTypeName.MatchString(r.Type):
		return fmt.Errorf("schema %s is recorded as %q, not a type name", r.Schema, r.Type)
	}
	return nil
}

var refTypeName = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*$`)

// checkGoTypes rejects a Go type record that names no type, stands for a
// type the family generates, or repeats a schema.
func checkGoTypes(fam *Family) error {
	seen := map[string]bool{}
	for _, g := range fam.GoTypes {
		switch {
		case !refTypeName.MatchString(g.Type):
			return fmt.Errorf("%s is recorded as Go type %q, not a type name", g.Schema, g.Type)
		case slices.Contains(fam.Types, g.Schema):
			return fmt.Errorf("%s is generated and recorded as Go type %s", g.Schema, g.Type)
		case seen[g.Schema]:
			return fmt.Errorf("%s is recorded twice", g.Schema)
		}
		seen[g.Schema] = true
	}
	return nil
}

// method collects the parts of one generated method.
type method struct {
	fam    *Family
	b      *OpBind
	op     *Operation
	params []string // signature after ctx
	result string   // "error" or "(*T, error)"
	pre    []string
}

func renderMethod(spec *Spec, fam *Family, b *OpBind) (string, error) {
	op, ok := spec.Operation(b.Operation)
	if !ok {
		return "", fmt.Errorf("operation not in spec")
	}
	if len(b.Params) != strings.Count(op.Path, "{")+len(b.Links) {
		return "", fmt.Errorf("%d params for path %s and %d links", len(b.Params), op.Path, len(b.Links))
	}
	switch b.Check {
	case checkInline, checkTrim, checkRequire, checkRaw:
	default:
		return "", fmt.Errorf("unknown check style %q", b.Check)
	}
	if b.IDList != nil && !strings.HasSuffix(op.Request, "LinkagesRequest") {
		return "", fmt.Errorf("idList needs a relationship change")
	}
	if b.CheckFirst && (op.Method != "GET" || b.Options == "" || (b.Check != checkTrim && b.Check != checkRequire)) {
		return "", fmt.Errorf("checkFirst needs a read with options and trim or require checks")
	}
	if b.Single && (op.Method != "GET" || b.Query == "" || b.NextContext != "") {
		return "", fmt.Errorf("single needs a read with a query builder and no next URL")
	}
	if len(b.Args) > 0 && !strings.HasSuffix(op.Request, "CreateRequest") && !strings.HasSuffix(op.Request, "UpdateRequest") {
		return "", fmt.Errorf("args need a create or update request")
	}
	write := (op.Method == "PATCH" && strings.HasSuffix(op.Request, "UpdateRequest")) ||
		(op.Method == "POST" && strings.HasSuffix(op.Request, "CreateRequest"))
	if (b.Attrs != "" || b.SkipEmptyAttributes) && !write {
		return "", fmt.Errorf("attributes bindings need a create or update request")
	}
	if b.ParseErr != "" && op.Method != "GET" && !write {
		return "", fmt.Errorf("parseErr needs a read, create or update that decodes its response")
	}
	m := &method{fam: fam, b: b, op: op}
	if params := b.stringParams(); len(params) > 0 {
		m.params = append(m.params, strings.Join(params, ", ")+" string")
	}
	response := b.Response
	if response == "" {
		response = fam.goType(op.Response)
	}

	var call string
	switch {
	case op.Method == "GET":
		if response == "" {
			return "", fmt.Errorf("no response schema")
		}
		call = m.read(response)
	case op.Method == "DELETE" && op.Request == "":
		m.result = "error"
		m.checks()
		call = fmt.Sprintf("return sendNoContent(ctx, c, http.MethodDelete, %s, nil)", m.path())
	case strings.HasSuffix(op.Request, "LinkagesRequest"):
		linkType, err := linkageType(spec, op.Request)
		if err != nil {
			return "", err
		}
		if b.IDs == "" {
			return "", fmt.Errorf("relationship change needs ids")
		}
		m.params = append(m.params, b.IDs+" []string")
		m.result = "error"
		m.checks()
		body, err := m.idList(resourceTypeConst(linkType))
		if err != nil {
			return "", err
		}
		call = fmt.Sprintf("return sendNoContent(ctx, c, http.Method%s, %s, %s)", methodConst(op.Method), m.path(), body)
	case write:
		if response == "" {
			return "", fmt.Errorf("no response schema")
		}
		m.result = "(*" + response + ", error)"
		payload, err := m.payload(spec)
		if err != nil {
			return "", err
		}
		m.pre = append(m.pre, payload)
		fields := []string{"Method: http.Method" + methodConst(op.Method), "Path: " + m.path(), "Payload: payload"}
		if b.ParseErr != "" {
			fields = append(fields, "ParseErr: "+strconv.Quote(b.ParseErr))
		}
		call = fmt.Sprintf("return sendJSON[%s](ctx, c, writeRequest{\n%s,\n})", response, strings.Join(fields, ",\n"))
	default:
		return "", fmt.Errorf("%s with request %q is not supported", op.Method, op.Request)
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// %s sends %s %s (%s).\n", b.Name, op.Method, op.Path, op.ID)
	fmt.Fprintf(&out, "func (c *Client) %s(%s) %s {\n", b.Name, strings.Join(append([]string{"ctx context.Context"}, m.params...), ", "), m.result)
	for _, line := range m.pre {
		out.WriteString(line + "\n")
	}
	out.WriteString(call + "\n}\n\n")
	return out.String(), nil
}

func (m *method) read(response string) string {
	m.result = "(*" + response + ", error)"
	fields := []string{"Path: " + m.path()}
	if m.b.CheckFirst {
		m.checks()
	}
	if m.b.Single {
		fields = append(fields, m.singleQuery())
	} else if m.b.Options != "" {
		m.params = append(m.params, "opts ..."+m.b.Options)
		m.pre = append(m.pre, "query := applyOptions(opts)")
		fields = append(fields, fmt.Sprintf("Query: %s(query)", m.b.Query), "Next: query.nextURL")
		if m.b.NextContext != "" {
			fields = append(fields, "NextContext: "+strconv.Quote(m.b.NextContext))
		}
	}
	if m.b.ParseErr != "" {
		fields = append(fields, "ParseErr: "+strconv.Quote(m.b.ParseErr))
	}
	if !m.b.CheckFirst {
		m.checks()
	}
	return fmt.Sprintf("return getJSON[%s](ctx, c, readRequest{\n%s,\n})", response, strings.Join(fields, ",\n"))
}

// singleQuery adds the query argument of a single read and returns its Query
// field: the options, or a fields list when there is no option type.
func (m *method) singleQuery() string {
	if m.b.Options == "" {
		m.params = append(m.params, "fields []string")
		return fmt.Sprintf("Query: %s(fields)", m.b.Query)
	}
	m.params = append(m.params, "opts ..."+m.b.Options)
	m.pre = append(m.pre, "query := applyOptions(opts)")
	return fmt.Sprintf("Query: %s(query)", m.b.Query)
}

// checks adds the trim and blank checks of the path parameters.
func (m *method) checks() {
	if m.b.Check == checkInline || m.b.Check == checkRaw {
		return
	}
	for _, p := range m.b.stringParams() {
		m.pre = append(m.pre, fmt.Sprintf("%s = strings.TrimSpace(%s)", p, p))
	}
	if m.b.Check != checkRequire {
		return
	}
	zero := ""
	if m.result != "error" {
		zero = "nil, "
	}
	for i, p := range m.b.stringParams() {
		msg := p + " is required"
		if i < len(m.b.Messages) {
			msg = m.b.Messages[i]
		}
		cond := p + ` == ""`
		if m.b.Options != "" && !m.b.CheckFirst && !m.b.Single {
			cond = `query.nextURL == "" && ` + cond
		}
		m.pre = append(m.pre, fmt.Sprintf("if %s {\nreturn %sfmt.Errorf(%s)\n}", cond, zero, strconv.Quote(msg)))
	}
}

// arg is a path parameter as the request uses it.
func (m *method) arg(i int) string {
	if m.b.Check == checkInline {
		return "strings.TrimSpace(" + m.b.Params[i] + ")"
	}
	return m.b.Params[i]
}

func (m *method) path() string {
	count := strings.Count(m.op.Path, "{")
	if count == 0 {
		return strconv.Quote(m.op.Path)
	}
	format := m.op.Path
	var args []string
	for i := range count {
		start := strings.Index(format, "{")
		end := strings.Index(format, "}")
		format = format[:start] + "%s" + format[end+1:]
		args = append(args, m.arg(i))
	}
	return fmt.Sprintf("fmt.Sprintf(%s, %s)", strconv.Quote(format), strings.Join(args, ", "))
}

// payload builds the create or update body; the attributes argument is
// always named attrs.
func (m *method) payload(spec *Spec) (string, error) {
	base := strings.TrimSuffix(m.op.Request, "Request")
	data, err := requestData(spec, m.op.Request)
	if err != nil {
		return "", err
	}
	typ := data.Properties.Get("type")
	if typ == nil || len(typ.Enum) != 1 {
		return "", fmt.Errorf("%s has no single type", m.op.Request)
	}
	var relationships string
	if rels := data.Properties.Get("relationships"); rels != nil {
		if relationships, err = m.relationships(rels); err != nil {
			return "", err
		}
	} else if len(m.b.Links) > 0 {
		return "", fmt.Errorf("%s has no relationships to link", m.op.Request)
	}
	fields := []string{"Type: " + resourceTypeConst(typ.Enum[0])}
	if data.Properties.Get("id") != nil {
		if len(m.b.Params) != 1 {
			return "", fmt.Errorf("update needs one path parameter")
		}
		fields = append(fields, "ID: "+m.arg(0))
	}
	if err := m.checkAttrs(data); err != nil {
		return "", err
	}
	var step string
	if len(m.b.Args) > 0 {
		if m.b.Attrs != "" || m.b.SkipEmptyAttributes {
			return "", fmt.Errorf("args take the place of the attributes argument")
		}
		attrs, err := m.argAttributes(data, base)
		if err != nil {
			return "", err
		}
		fields = append(fields, attrs)
	} else if attrs := data.Properties.Get("attributes"); attrs != nil {
		typ := m.fam.goType(base + "Attributes")
		if m.b.Attrs == attrsPointer {
			typ = "*" + typ
		}
		m.params = append(m.params, "attrs "+typ)
		switch {
		case m.b.SkipEmptyAttributes:
			step = "\n" + attributesIfSet(attrs)
		case data.requires("attributes") || m.b.Attrs != "":
			fields = append(fields, "Attributes: attrs")
		default:
			fields = append(fields, "Attributes: &attrs")
		}
	}
	if relationships != "" {
		fields = append(fields, "Relationships: "+relationships)
	}
	m.checks()
	return fmt.Sprintf("payload := %s{\nData: %s{\n%s,\n},\n}", m.fam.goType(m.op.Request), m.fam.goType(base+"Data"), strings.Join(fields, ",\n")) + step, nil
}

// checkAttrs rejects attributes bindings the request data cannot take.
func (m *method) checkAttrs(data *Schema) error {
	attrs := data.Properties.Get("attributes")
	optional := attrs != nil && !data.requires("attributes")
	switch m.b.Attrs {
	case "":
	case attrsValue, attrsPointer:
		if !optional {
			return fmt.Errorf("attrs %q needs optional attributes", m.b.Attrs)
		}
	default:
		return fmt.Errorf("unknown attrs %q", m.b.Attrs)
	}
	if m.b.SkipEmptyAttributes && (!optional || m.b.Attrs != "" || len(attrs.Required) > 0 || len(attrs.Properties) == 0) {
		return fmt.Errorf("skipEmptyAttributes needs optional attributes, none of them required, passed by value")
	}
	return nil
}

// attributesIfSet attaches the attributes only when one of them is set. No
// attribute is required, so a request attributes type holds each as a
// nillable field.
func attributesIfSet(attrs *Schema) string {
	var set []string
	for _, prop := range attrs.Properties {
		set = append(set, "attrs."+goName(prop.Name)+" != nil")
	}
	return fmt.Sprintf("if %s {\npayload.Data.Attributes = &attrs\n}", strings.Join(set, " || "))
}

// relationships renders the relationships of a create, one to-one link for
// each of the last len(Links) parameters.
func (m *method) relationships(rels *Schema) (string, error) {
	if m.op.Method != "POST" || len(m.b.Links) == 0 {
		return "", fmt.Errorf("relationships in %s need a create with links", m.op.Request)
	}
	rel, err := m.fam.relationshipsOf(strings.TrimSuffix(m.op.Request, "Request") + "Data")
	if err != nil {
		return "", err
	}
	for _, name := range rels.Required {
		if !slices.Contains(m.b.Links, name) {
			return "", fmt.Errorf("required relationship %q is not linked", name)
		}
	}
	first := len(m.b.Params) - len(m.b.Links)
	var links []string
	for i, name := range m.b.Links {
		typ, err := linkType(rel, rels, name)
		if err != nil {
			return "", err
		}
		resource := rels.Properties.Get(name).Properties.Get("data").Properties.Get("type")
		if strings.HasSuffix(typ, "List") || resource == nil || len(resource.Enum) != 1 {
			return "", fmt.Errorf("%s has no to-one relationship %q of one type", m.op.Request, name)
		}
		if slices.Contains(m.b.Links[:i], name) {
			return "", fmt.Errorf("relationship %q is linked twice", name)
		}
		links = append(links, fmt.Sprintf("%s: %s{\nData: ResourceData{\nType: %s,\nID: %s,\n},\n}", goName(name), addressOf(typ), resourceTypeConst(resource.Enum[0]), m.arg(first+i)))
	}
	return fmt.Sprintf("%s{\n%s,\n}", addressOf(rel.Type), strings.Join(links, ",\n")), nil
}

// addressOf turns a type such as "*T" into the start of a literal, "&T".
func addressOf(typ string) string {
	if t, ok := strings.CutPrefix(typ, "*"); ok {
		return "&" + t
	}
	return typ
}

// idList adds the ID list handling of a relationship change after the path
// parameter checks and returns the request body expression.
func (m *method) idList(typ string) (string, error) {
	ids, l := m.b.IDs, m.b.IDList
	if l == nil {
		l = &IDList{}
	}
	if l.Message != "" && !l.Normalize {
		return "", fmt.Errorf("an empty ID list message needs normalize")
	}
	if loop := l.Payload == payloadAppend || l.Payload == payloadResourceList; loop != (l.Item != "") {
		return "", fmt.Errorf("payload %q with item %q", l.Payload, l.Item)
	}
	if l.Normalize {
		at := 0
		if m.b.Check == checkTrim || m.b.Check == checkRequire {
			at = len(m.b.Params)
		}
		m.pre = slices.Insert(m.pre, at, fmt.Sprintf("%s = normalizeList(%s)", ids, ids))
	}
	if l.Message != "" {
		m.pre = append(m.pre, fmt.Sprintf("if len(%s) == 0 {\nreturn fmt.Errorf(%s)\n}", ids, strconv.Quote(l.Message)))
	}
	switch l.Payload {
	case payloadDefault:
		m.pre = append(m.pre, fmt.Sprintf("payload := RelationshipRequest{\nData: buildRelationshipData(%s, %s),\n}", typ, ids))
	case payloadAppend:
		m.pre = append(m.pre, fmt.Sprintf("payload := RelationshipRequest{\nData: make([]RelationshipData, 0, len(%s)),\n}\nfor _, %s := range %s {\npayload.Data = append(payload.Data, RelationshipData{\nType: %s,\nID: %s,\n})\n}", ids, l.Item, ids, typ, l.Item))
	case payloadIndex:
		m.pre = append(m.pre, fmt.Sprintf("payload := RelationshipRequest{\nData: make([]RelationshipData, len(%s)),\n}\nfor i, id := range %s {\npayload.Data[i] = RelationshipData{\nType: %s,\nID: id,\n}\n}", ids, ids, typ))
	case payloadResourceList:
		m.pre = append(m.pre, fmt.Sprintf("relData := make([]ResourceData, 0, len(%s))\nfor _, %s := range %s {\nrelData = append(relData, ResourceData{\nType: %s,\nID: %s,\n})\n}", ids, l.Item, ids, typ, l.Item))
		return "RelationshipList{Data: relData}", nil
	case payloadNonNil:
		m.pre = append(m.pre, fmt.Sprintf("data := buildRelationshipData(%s, %s)\nif data == nil {\ndata = []RelationshipData{}\n}\npayload := RelationshipRequest{Data: data}", typ, ids))
	default:
		return "", fmt.Errorf("unknown ID list payload %q", l.Payload)
	}
	return "payload", nil
}

// checkArgTypes rejects an arg with its own Go type when the family also
// generates the attributes type it sets, which declares the field with the
// attribute's default type.
func checkArgTypes(spec *Spec, fam *Family) error {
	for _, b := range fam.Operations {
		op, ok := spec.Operation(b.Operation)
		if !ok {
			continue
		}
		attrs := strings.TrimSuffix(op.Request, "Request") + "Attributes"
		for _, arg := range b.Args {
			if arg.Type != "" && slices.Contains(fam.Types, attrs) {
				return fmt.Errorf("%s: arg %s is %s, but %s is generated with the attribute's type", b.Operation, arg.Name, arg.Type, attrs)
			}
		}
	}
	return nil
}

// argAttributes sets each argument as its attribute, in argument order:
// required attributes by value, optional ones by pointer.
func (m *method) argAttributes(data *Schema, base string) (string, error) {
	attrs := data.Properties.Get("attributes")
	if attrs == nil {
		return "", fmt.Errorf("args need request attributes")
	}
	seen := map[string]bool{}
	var fields []string
	for i, arg := range m.b.Args {
		name := arg.Attribute
		if name == "" {
			name = arg.Name
		}
		prop := attrs.Properties.Get(name)
		if prop == nil || seen[name] {
			return "", fmt.Errorf("arg %s: no attribute %q or set twice", arg.Name, name)
		}
		seen[name] = true
		typ, scalar, err := goType(prop)
		switch {
		case err != nil || !scalar:
			return "", fmt.Errorf("arg %s: attribute %q is not a scalar", arg.Name, name)
		case arg.Param:
			if err := m.checkParamArg(i, typ); err != nil {
				return "", err
			}
		case arg.Type == "int64" && typ == "int":
			typ = arg.Type
		case arg.Type != "" && typ == "string" && len(prop.Enum) > 0 && refTypeName.MatchString(arg.Type):
			typ = arg.Type
		case arg.Type != "":
			return "", fmt.Errorf("arg %s: type %s does not fit attribute %q", arg.Name, arg.Type, name)
		}
		if !arg.Param {
			m.params = append(m.params, arg.Name+" "+typ)
		}
		value := arg.Name
		if !attrs.requires(name) {
			value = "&" + value
		}
		fields = append(fields, goName(name)+": "+value)
	}
	lit := fmt.Sprintf("%s{\n%s,\n}", m.fam.goType(base+"Attributes"), strings.Join(fields, ",\n"))
	if data.requires("attributes") {
		return "Attributes: " + lit, nil
	}
	return "Attributes: &" + lit, nil
}

// stringParams are the Params, then the param args: the string parameters
// declared in one group and checked alike.
func (b *OpBind) stringParams() []string {
	params := slices.Clone(b.Params)
	for _, arg := range b.Args {
		if arg.Param {
			params = append(params, arg.Name)
		}
	}
	return params
}

// checkParamArg rejects a param arg the string parameter group cannot hold:
// one for an attribute that is no string, with its own type, after an arg
// that is no param arg, or one the inline check style would not trim before
// use.
func (m *method) checkParamArg(i int, typ string) error {
	arg := m.b.Args[i]
	switch {
	case typ != "string" || arg.Type != "":
		return fmt.Errorf("arg %s: a param arg needs a string attribute and no Go type of its own", arg.Name)
	case slices.ContainsFunc(m.b.Args[:i], func(a ArgBind) bool { return !a.Param }):
		return fmt.Errorf("arg %s: param args come before the other args", arg.Name)
	case m.b.Check == checkInline:
		return fmt.Errorf("arg %s: param args need the trim, require or raw check style", arg.Name)
	}
	return nil
}

func linkageType(spec *Spec, request string) (string, error) {
	sch, ok := spec.Schema(request)
	if !ok {
		return "", fmt.Errorf("no schema %s", request)
	}
	data := sch.Properties.Get("data")
	if data == nil || data.Items == nil || data.Items.Properties.Get("type") == nil || len(data.Items.Properties.Get("type").Enum) != 1 {
		return "", fmt.Errorf("%s is not a to-many linkage request", request)
	}
	return data.Items.Properties.Get("type").Enum[0], nil
}

func methodConst(method string) string {
	return upperFirst(strings.ToLower(method))
}
